defmodule Mana.Boot do
  @moduledoc """
  Release-style boot generation for the closed world.

  A BEAM release boots through the application controller. The controller
  walks the `.app` specs, applies the config, starts every application in the
  dependency tree in order through its `mod:` callback, then parks. The closed
  world has no application controller and no files at run time. For this
  reason `mix mana.compile --app` computes that walk at build time into a
  generated `Mana.AppBoot` module:

    * The merged compile-time config (`.app` env defaults ⊕ config.exs ⊕
      `\#{MIX_ENV}.exs`) is baked as `Application.put_env` data. This is the
      equivalent of the sys.config of a release.
    * Applications start in dependency order by direct
      `Mod.start(:normal, args)` calls. The application cut has no
      controller. `ensure_all_started` and related functions do not exist.
    * `main/0` starts everything and parks forever (`--no-halt`).

  The module is compiled to a beam (with debug_info) into the out dir. So it
  flows through the normal beam → core → manac pipeline, and the BEAM oracle
  can run the same module.
  """

  # Never started: runtime-cut, BEAM-infra, and build-tool applications.
  # Their code is native (cut modules) or has no meaning without the BEAM.
  # phoenix_live_reload and file_system are dev watchers over source files.
  # A native binary has no source and nothing to reload.
  @skip ~w(kernel stdlib elixir logger crypto ssl sasl compiler
           runtime_tools inets os_mon public_key asn1 mix iex ex_unit eex
           phoenix_live_reload file_system)a

  @doc """
  Scrub dev-only, build-tool-backed config from the application env of the
  task VM BEFORE `Mix.Task.run("compile")`. Some modules consumed these keys
  through `Application.compile_env` (Phoenix endpoints bake :code_reloader
  into call/2). The compile-env tracking of Mix recompiles those modules. So
  the compiled beams get release semantics on both runtimes.
  """
  def scrub_compile_env! do
    app = Mix.Project.config()[:app]

    if app do
      _ = Application.load(app)

      for {key, value} <- Application.get_all_env(app) do
        scrubbed = scrub(app, key, value)
        if scrubbed != value, do: Application.put_env(app, key, scrubbed)
      end
    end

    :ok
  end

  @doc """
  Generate `Mana.AppBoot` for the application of the current Mix project and
  write its beam into `out_dir`. Returns the beam path.
  """
  def generate!(out_dir) do
    app =
      Mix.Project.config()[:app] ||
        Mix.raise("mana: --app requires a project with an :app name")

    {order, env_only} = closure(app)

    env_calls =
      for a <- order ++ env_only, {k, v} <- Application.get_all_env(a) do
        v = scrub(a, k, v)

        quote do
          Application.put_env(unquote(a), unquote(k), unquote(escape_env!(a, k, v)))
        end
      end

    start_calls =
      for a <- order, spec = Application.spec(a, :mod), match?({_, _}, spec) do
        {mod, args} = spec

        quote do
          {:ok, _} = unquote(mod).start(:normal, unquote(Macro.escape(args)))
        end
      end

    # Real per-app dirs for code:lib_dir/priv_dir (Plug.Static resolves
    # priv/static through them). These are build-machine paths, like the lib
    # dir of a release. TODO(embed-priv): embed static assets into the binary.
    dir_calls =
      for a <- order ++ env_only, dir = app_dir(a), dir != nil do
        quote do
          Application.put_env(:mana_app_dirs, unquote(a), unquote(dir))
        end
      end

    env_calls = env_calls ++ dir_calls

    runtime_body = runtime_config_body()

    ast =
      quote do
        defmodule Mana.AppBoot do
          @moduledoc false

          # Generated by mix mana.compile --app. Do not edit.
          def start_all do
            (unquote_splicing(env_calls))
            runtime_config()
            (unquote_splicing(start_calls))
            :ok
          end

          def main do
            start_all()
            IO.puts("mana: #{unquote(app)} running (ctrl-c to stop)")
            Process.sleep(:infinity)
          end

          # config/runtime.exs is compiled in. A release evaluates it at every
          # boot (System.get_env reads the REAL environment). Here its AST is
          # spliced over a local mini-Config DSL. The DSL has the same deep
          # keyword-merge semantics and runs at native boot.
          defp runtime_config do
            # Reference the whole DSL so that unused arities do not warn.
            _ = {&config_env/0, &config/2, &config/3}
            unquote(runtime_body)
            :ok
          end

          defp config_env, do: unquote(Mix.env())

          defp config(app, opts) do
            Enum.each(opts, fn {k, v} ->
              Application.put_env(app, k, merge_env(Application.get_env(app, k), v))
            end)
          end

          defp config(app, key, value) do
            Application.put_env(app, key, merge_env(Application.get_env(app, key), value))
          end

          defp merge_env(old, new) do
            if Keyword.keyword?(old) and Keyword.keyword?(new) do
              Keyword.merge(old, new, fn _k, o, n -> merge_env(o, n) end)
            else
              new
            end
          end

        end
      end

    old = Code.get_compiler_option(:debug_info)
    Code.put_compiler_option(:debug_info, true)

    try do
      [{mod, beam} | _] = Code.compile_quoted(ast, "mana_app_boot.ex")
      path = Path.join(out_dir, "#{mod}.beam")
      File.write!(path, beam)
      path
    after
      Code.put_compiler_option(:debug_info, old)
    end
  end

  # config/runtime.exs → quoted body for the generated runtime_config/0.
  # `import Config` statements are removed (config/2,3 and config_env/0
  # resolve to the locals of the generated module). import_config is rejected.
  defp runtime_config_body do
    path = Path.join([Path.dirname(Mix.Project.project_file()), "config", "runtime.exs"])

    if File.exists?(path) do
      ast = Code.string_to_quoted!(File.read!(path), file: path)

      Macro.prewalk(ast, fn
        {:import_config, meta, [_ | _]} ->
          Mix.raise(
            "mana: import_config in config/runtime.exs:#{meta[:line]} is not " <>
              "supported in a native binary (no files at runtime)"
          )

        node ->
          node
      end)
      |> strip_import_config()
    else
      :ok
    end
  end

  defp strip_import_config({:__block__, meta, stmts}) do
    {:__block__, meta, Enum.reject(stmts, &config_import?/1)}
  end

  defp strip_import_config(ast) do
    if config_import?(ast), do: :ok, else: ast
  end

  defp config_import?({:import, _, [{:__aliases__, _, [:Config]} | _]}), do: true
  defp config_import?(_), do: false

  # Dependencies-first application order: post-order DFS over the
  # `applications:` lists of the `.app` specs. Skip-listed apps are never
  # STARTED but their env is still baked (compiled code reads, for example,
  # the :truncate key of :logger). Build tools are the exception. They never
  # ship.
  @no_env ~w(mix iex ex_unit eex)a

  defp closure(root) do
    {order, seen} = visit(root, [], MapSet.new())

    env_only =
      for a <- MapSet.to_list(seen) -- order,
          a not in @no_env,
          loadable?(a),
          do: a

    {order, Enum.sort(env_only)}
  end

  defp visit(app, order, seen) do
    cond do
      MapSet.member?(seen, app) ->
        {order, seen}

      app in @skip ->
        {order, MapSet.put(seen, app)}

      not loadable?(app) ->
        # Not a real application, or not present in this build. The closed
        # world compiles only what reachability pulls in any case.
        {order, MapSet.put(seen, app)}

      true ->
        seen = MapSet.put(seen, app)
        deps = Application.spec(app, :applications) || []
        {order, seen} = Enum.reduce(deps, {order, seen}, fn d, {o, s} -> visit(d, o, s) end)
        {order ++ [app], seen}
    end
  end

  defp app_dir(app) do
    to_string(Application.app_dir(app))
  rescue
    _ -> nil
  end

  defp loadable?(app) do
    case Application.load(app) do
      :ok -> true
      {:error, {:already_loaded, _}} -> true
      _ -> false
    end
  end

  defp escape_env!(app, key, value) do
    Macro.escape(value)
  rescue
    e in ArgumentError ->
      Mix.raise(
        "mana: config value for #{inspect(app)} / #{inspect(key)} cannot be " <>
          "embedded in the boot module (#{Exception.message(e)}). Only literal " <>
          "terms can be baked. Move it to config/runtime.exs or to start/2 of the app."
      )
  end

  # Dev-config features that build tools back cannot exist in a native
  # binary. There is no Mix and nothing to reload. A BEAM release built with
  # dev config also crashes on these keys. Scrub them loudly instead of a
  # crash at boot.
  @dev_only [:code_reloader, :live_reload, :watchers]

  defp scrub(app, key, value) when is_list(value) do
    if Keyword.keyword?(value) and Enum.any?(@dev_only, &Keyword.has_key?(value, &1)) do
      dropped = Enum.filter(@dev_only, &Keyword.has_key?(value, &1))

      Mix.shell().info(
        "mana: dropped dev-only config #{inspect(dropped)} from " <>
          "#{inspect(app)} / #{inspect(key)}. Build tooling is not available in a native binary."
      )

      Keyword.drop(value, @dev_only)
    else
      value
    end
  end

  defp scrub(_app, _key, value), do: value
end
